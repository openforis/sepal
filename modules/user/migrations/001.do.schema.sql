-- User schema at its full current shape.
--
-- Usernames and emails identify people, so their comparisons and UNIQUE indexes ignore case (citext).

CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE sepal_user (
  id                             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username                       citext        NOT NULL CHECK (char_length(username) <= 32),
  name                           varchar(1000),
  email                          citext        CHECK (char_length(email) <= 255),
  organization                   varchar(1000),
  token                          varchar(256),
  admin                          boolean       NOT NULL,
  "system_user"                 boolean       NOT NULL,
  status                         varchar(32)   NOT NULL,
  google_refresh_token           varchar(128),
  google_access_token            varchar(256),
  google_access_token_expiration timestamptz(0),
  creation_time                  timestamptz(0) NOT NULL DEFAULT now(),
  update_time                    timestamptz(0) NOT NULL DEFAULT now(),
  token_generation_time          timestamptz(0) NOT NULL DEFAULT now(),
  last_login_time                timestamptz(0),
  email_notifications_enabled    boolean       DEFAULT true,
  intended_use                   text,
  google_project_id              varchar(1024),
  google_legacy_project          boolean       DEFAULT false,
  manual_map_rendering_enabled   boolean       DEFAULT false,
  privacy_policy_accepted        boolean       DEFAULT false,
  password_hash                  varchar(255),
  ssh_public_key                 text,
  uid                            integer,
  gid                            integer,
  revision                       integer       NOT NULL DEFAULT 1 CHECK (revision >= 0)
);

CREATE UNIQUE INDEX sepal_user_idx_sepal_user_2 ON sepal_user (username);
CREATE UNIQUE INDEX sepal_user_idx_sepal_user_4 ON sepal_user (token);
CREATE UNIQUE INDEX sepal_user_idx_sepal_user_3 ON sepal_user (email);
CREATE INDEX sepal_user_idx_sepal_user_1 ON sepal_user (creation_time);

-- Keys users register for SSH logins, alongside the SEPAL-generated key in sepal_user.ssh_public_key.
-- public_key is the base64 blob alone: nothing the user typed around it is kept.
CREATE TABLE ssh_key (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      citext        NOT NULL CHECK (char_length(username) <= 32),
  name          varchar(255)  NOT NULL,
  key_type      varchar(64)   NOT NULL,
  public_key    text          NOT NULL,
  fingerprint   varchar(64)   NOT NULL,
  creation_time timestamptz(0) NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX ssh_key_idx_ssh_key_1 ON ssh_key (username, fingerprint);
