-- Restoring fails for a row inserted into an always-generated identity unless the restore overrides it.
CREATE TABLE reference_item (
  id   integer     GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name varchar(64) NOT NULL
);

-- The counter is set past the largest stored id, as if a third row had been inserted and removed, so the
-- baseline counter (next id 31) cannot be derived from the rows; only restoring the counter reproduces it.
INSERT INTO reference_item (id, name) OVERRIDING SYSTEM VALUE VALUES (10, 'first'), (20, 'second');
SELECT setval(pg_get_serial_sequence('reference_item', 'id'), 30);

CREATE TABLE recorded_event (
  id   varchar(36) NOT NULL PRIMARY KEY,
  note varchar(64) NOT NULL
);

-- Never drawn from before the baseline.
CREATE TABLE numbered_note (
  id   integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  note varchar(64) NOT NULL
);
