CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE IF NOT EXISTS history (
  id        integer        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username  citext         NOT NULL CHECK (char_length(username) <= 32),
  event     varchar(64)    NOT NULL,
  timestamp timestamptz(0) NOT NULL
);

CREATE INDEX history_idx_history_1 ON history (username, timestamp, id);

CREATE INDEX history_idx_history_2 ON history (timestamp);
